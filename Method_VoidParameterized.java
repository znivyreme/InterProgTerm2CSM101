package Inter;
public class Method_VoidParameterized {
	static void DisplayStud(String name, int yearlvl) { 
		System.out.println("Student: " + name);
		System.out.println("Year Level: " + yearlvl);
	}
	public static void main (String [] args) {
		DisplayStud("Luzon ", 1);
		DisplayStud("ELijah ", 4);
		DisplayStud("Carlito  ", 3);
		}
	}

